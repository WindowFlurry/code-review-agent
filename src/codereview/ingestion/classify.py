"""File classification: language, tests, vendored code, generated code.

Generated and vendored files are excluded from review by default. Reporting a
defect in a checked-in ``*_pb2.py`` is noise the user cannot act on, and it
dilutes the precision figure in the evaluation.
"""

from __future__ import annotations

from pathlib import Path

#: Extension -> language name. Only Python gets deep analysis; the rest are
#: listed so ingestion can report what it skipped and why.
LANGUAGES: dict[str, str] = {
    ".py": "python",
    ".pyi": "python",
    ".js": "javascript",
    ".jsx": "javascript",
    ".ts": "typescript",
    ".tsx": "typescript",
    ".java": "java",
    ".c": "c",
    ".h": "c",
    ".cpp": "cpp",
    ".cc": "cpp",
    ".hpp": "cpp",
    ".cs": "csharp",
    ".go": "go",
    ".rs": "rust",
    ".rb": "ruby",
    ".php": "php",
    ".swift": "swift",
    ".kt": "kotlin",
    ".sh": "shell",
    ".sql": "sql",
    ".html": "html",
    ".css": "css",
    ".json": "json",
    ".yaml": "yaml",
    ".yml": "yaml",
    ".toml": "toml",
    ".md": "markdown",
}

#: Path fragments indicating a test file.
_TEST_MARKERS = ("test_", "_test.py", "tests/", "/tests", "conftest.py", "spec.")

#: Path fragments indicating checked-in third-party code.
_VENDOR_MARKERS = ("vendor/", "third_party/", "site-packages/", "node_modules/", "external/")

#: Substrings in the first lines that mark a file as machine-generated.
_GENERATED_MARKERS = (
    "do not edit",
    "auto-generated",
    "autogenerated",
    "generated by",
    "@generated",
    "this file is generated",
)


def detect_language(path: str | Path) -> str:
    return LANGUAGES.get(Path(path).suffix.lower(), "unknown")


def is_test_file(path: str | Path) -> bool:
    posix = str(path).replace("\\", "/").lower()
    name = Path(path).name.lower()
    return any(marker in posix for marker in _TEST_MARKERS) or name.startswith("test_")


def is_vendored(path: str | Path) -> bool:
    posix = str(path).replace("\\", "/").lower()
    return any(marker in posix for marker in _VENDOR_MARKERS)


def is_generated(head: str) -> bool:
    """True if the first few lines contain a 'do not edit' style marker.

    Only the head is inspected: scanning a whole file for the word "generated"
    would misfire on any file that mentions it in a comment.
    """
    header = "\n".join(head.splitlines()[:15]).lower()
    return any(marker in header for marker in _GENERATED_MARKERS)


def classify_path(path: str | Path) -> dict[str, object]:
    """Summarise a path for ingestion bookkeeping."""
    return {
        "language": detect_language(path),
        "is_test": is_test_file(path),
        "is_vendored": is_vendored(path),
    }
