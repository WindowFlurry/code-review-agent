"""Graph assembly -- the centrepiece of the architecture.

    START
      |
    [ingest]        deterministic: inventory the repo
      |             (empty repo -> straight to report)
    [static_scan]   deterministic: ruff + AST over everything
      |
    [plan]          LLM: prioritised task list, plus the deterministic findings
      |
    <fanout>        map: one Send per task, run concurrently
      |
    [review_file]   ReAct sub-agent per file, tools included
      |             -> evidence binding (snippet re-read from disk)
    [verify]        reflection: adversarial second agent refutes each claim
      |
    [aggregate]     reduce: dedup, sort, cap
      |
    [report]        render
      |
     END

Design patterns, for the write-up: ReAct (the reviewer loop), Reflection /
Generator-Verifier (the verify node), Map-Reduce fan-out (Send + `operator.add`
reducers), Plan-and-Execute (plan then fan out), Tool use as grounding, and
fail-closed guardrails (evidence binding rejects rather than trusts).

The split between deterministic and LLM nodes is the point. Anything that can be
computed exactly -- file inventory, lint results, line numbers, snippet
matching -- is computed exactly. The model is reserved for judgement, and every
judgement it makes is checkable against something that was not generated by a
model.
"""

from __future__ import annotations

import logging
from pathlib import Path

from langgraph.graph import END, START, StateGraph
from langgraph.types import RetryPolicy

from ..config import Settings, get_settings
from .nodes import (
    aggregate_node,
    fanout,
    ingest_node,
    plan_node,
    report_node,
    review_file_node,
    route_after_ingest,
    static_scan_node,
    verify_node,
)
from .state import ReviewState, empty_state

logger = logging.getLogger(__name__)

#: Node-level retry policy. Deliberately shallow, because the reviewer's own
#: middleware already retries model calls -- stacking deep retries here would
#: multiply into a burst of API calls on a single transient failure.
_NODE_RETRY = RetryPolicy(
    max_attempts=2,
    initial_interval=1.0,
    backoff_factor=2.0,
    jitter=True,
)


def build_graph(
    *,
    checkpointer=None,
    settings: Settings | None = None,
):
    """Build and compile the review graph.

    Args:
        checkpointer: Optional LangGraph checkpointer. Supplying one makes the
            run resumable and lets a follow-up Q&A agent attach to the same
            thread. Defaults to no persistence.
        settings: Injected for tests.
    """
    settings = settings or get_settings()

    graph = StateGraph(ReviewState)

    # --- deterministic phase: no tokens spent ---
    graph.add_node("ingest", ingest_node)
    graph.add_node("static_scan", static_scan_node)

    # --- LLM phase ---
    graph.add_node("plan", plan_node, retry_policy=_NODE_RETRY)
    graph.add_node("review_file", review_file_node, retry_policy=_NODE_RETRY)
    graph.add_node("verify", verify_node, retry_policy=_NODE_RETRY)

    # --- deterministic reduce ---
    graph.add_node("aggregate", aggregate_node)
    graph.add_node("report", report_node)

    graph.add_edge(START, "ingest")

    # An empty or unreadable repository short-circuits past every LLM call.
    graph.add_conditional_edges(
        "ingest",
        route_after_ingest,
        {"static_scan": "static_scan", "report": "report"},
    )

    graph.add_edge("static_scan", "plan")

    # Map: one concurrent reviewer per task. Falls through to `verify` when the
    # plan is empty, so tool-sourced findings still reach the report.
    graph.add_conditional_edges(
        "plan",
        fanout,
        {"review_file": "review_file", "verify": "verify"},
    )

    # Implicit barrier: every parallel `review_file` invocation completes and its
    # writes are merged before `verify` runs.
    graph.add_edge("review_file", "verify")
    graph.add_edge("verify", "aggregate")
    graph.add_edge("aggregate", "report")
    graph.add_edge("report", END)

    compiled = graph.compile(checkpointer=checkpointer)
    logger.debug("graph compiled (checkpointer=%s)", type(checkpointer).__name__ if checkpointer else "none")
    return compiled


def run_graph(
    repo_root: Path | str,
    *,
    run_id: str = "run",
    checkpointer=None,
    offline: bool = False,
    settings: Settings | None = None,
) -> ReviewState:
    """Run a full review and return the final state."""
    settings = settings or get_settings()
    root = Path(repo_root).resolve()

    graph = build_graph(checkpointer=checkpointer, settings=settings)
    initial = empty_state(str(root), run_id, offline=offline)

    config = {"configurable": {"thread_id": run_id}, "recursion_limit": 200}

    logger.info("starting review of %s (run_id=%s)", root, run_id)
    return graph.invoke(initial, config)
