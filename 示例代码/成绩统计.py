# 学生成绩统计小程序
# 这是一段典型的初学者代码，里面有几个常见错误，可以用它来试审查助手

def 平均分(分数列表):
    return sum(分数列表) / len(分数列表)


def 最高分(分数列表):
    最大值 = 0
    for 分数 in 分数列表:
        if 分数 > 最大值:
            最大值 = 分数
    return 最大值


def 等级(分数):
    if 分数 >= 90:
        return "优秀"
    elif 分数 >= 80:
        return "良好"
    elif 分数 >= 60:
        return "及格"


def 主程序():
    成绩 = [88, 92, 75, 60, 95]
    print("平均分：", 平均分(成绩))
    print("最高分：", 最高分(成绩))

    for 分数 in 成绩:
        print(分数, 等级(分数))


主程序()
