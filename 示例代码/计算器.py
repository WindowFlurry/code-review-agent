# 简易计算器
# 这个文件的错误更隐蔽：语法完全正确，但逻辑不对

def 计算(第一个数, 第二个数, 运算符):
    if 运算符 == "+":
        return 第一个数 + 第二个数
    elif 运算符 == "-":
        return 第一个数 - 第二个数
    elif 运算符 == "*":
        return 第一个数 * 第二个数
    elif 运算符 == "/":
        return 第一个数 / 第二个数


def 主程序():
    第一个数 = input("请输入第一个数：")
    第二个数 = input("请输入第二个数：")

    结果 = 计算(第一个数, 第二个数, "+")
    print("结果是：", 结果)


主程序()
