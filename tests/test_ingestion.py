"""Repository ingestion and edge-case classification.

These are the cases that make a review agent fall over in practice: a binary
file with a .py extension, a UTF-16 source file, an empty file, something larger
than the size cap, and an empty repository.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from codereview.errors import IngestionError
from codereview.ingestion import chunk_lines, walk_repo


def by_path(metas) -> dict:
    return {m.path: m for m in metas}


def test_classifies_each_edge_case(weird_repo: Path) -> None:
    metas = by_path(walk_repo(weird_repo, max_files=40))

    assert metas["binary.py"].skip_reason == "binary"
    assert metas["empty.py"].skip_reason == "empty"
    assert metas["huge.py"].skip_reason == "too_large"
    # UTF-16 is text, not binary, despite the NUL bytes in its ASCII range.
    assert not metas["utf16_encoded.py"].skipped


def test_decodes_non_utf8_encodings(weird_repo: Path) -> None:
    metas = by_path(walk_repo(weird_repo, max_files=40))

    assert metas["gbk_encoded.py"].encoding == "gbk"
    assert metas["utf16_encoded.py"].encoding == "utf-16"


def test_syntax_error_file_is_still_reviewable(weird_repo: Path) -> None:
    """A file that will not parse is the most important thing in it."""
    metas = by_path(walk_repo(weird_repo, max_files=40))

    assert not metas["syntax_error.py"].skipped


def test_skips_non_python(clean_repo: Path) -> None:
    metas = by_path(walk_repo(clean_repo, max_files=40))

    assert metas["README.md"].skip_reason == "not_python"


def test_records_hash_and_line_count(clean_repo: Path) -> None:
    metas = by_path(walk_repo(clean_repo, max_files=40))

    assert metas["arithmetic.py"].line_count > 40
    assert len(metas["arithmetic.py"].sha256) == 64


def test_empty_directory_returns_nothing(tmp_path: Path) -> None:
    assert walk_repo(tmp_path) == []


def test_missing_directory_raises(tmp_path: Path) -> None:
    with pytest.raises(IngestionError, match="does not exist"):
        walk_repo(tmp_path / "nope")


def test_file_as_root_raises(tmp_path: Path) -> None:
    target = tmp_path / "file.py"
    target.write_text("x = 1", encoding="utf-8")

    with pytest.raises(IngestionError, match="not a directory"):
        walk_repo(target)


def test_max_files_cap_is_enforced(tmp_path: Path) -> None:
    for index in range(10):
        (tmp_path / f"mod_{index}.py").write_text(f"x = {index}\n", encoding="utf-8")

    metas = walk_repo(tmp_path, max_files=3)
    reviewable = [m for m in metas if m.reviewable]

    assert len(reviewable) == 3
    # The remainder must be recorded as skipped, not silently dropped.
    assert len([m for m in metas if m.skipped]) >= 7


def test_ignores_virtualenv_and_caches(tmp_path: Path) -> None:
    (tmp_path / "app.py").write_text("x = 1\n", encoding="utf-8")
    for directory in (".venv", "__pycache__", ".git", "node_modules"):
        nested = tmp_path / directory
        nested.mkdir()
        (nested / "hidden.py").write_text("y = 2\n", encoding="utf-8")

    paths = {m.path for m in walk_repo(tmp_path)}

    assert paths == {"app.py"}


def test_generated_file_is_skipped(tmp_path: Path) -> None:
    (tmp_path / "proto_pb2.py").write_text(
        "# Generated by the protocol buffer compiler.  DO NOT EDIT!\nX = 1\n",
        encoding="utf-8",
    )

    metas = by_path(walk_repo(tmp_path))

    assert metas["proto_pb2.py"].skip_reason == "generated"


# --- chunking -------------------------------------------------------------


def test_short_file_is_not_chunked() -> None:
    chunks = chunk_lines(100)

    assert len(chunks) == 1
    assert chunks[0].line_start == 1
    assert chunks[0].line_end == 100


def test_long_file_is_split_with_overlap() -> None:
    chunks = chunk_lines(2000, window=400, overlap=40, threshold=450)

    assert len(chunks) > 1
    assert chunks[0].line_start == 1
    assert chunks[-1].line_end == 2000
    # Consecutive windows overlap, so a defect spanning a boundary is still seen.
    assert chunks[1].line_start < chunks[0].line_end


def test_chunks_cover_every_line() -> None:
    chunks = chunk_lines(2000, window=400, overlap=40, threshold=450)
    covered: set[int] = set()
    for chunk in chunks:
        covered.update(range(chunk.line_start, chunk.line_end + 1))

    assert covered == set(range(1, 2001))


def test_zero_lines_returns_no_chunks() -> None:
    assert chunk_lines(0) == []


def test_overlap_larger_than_window_is_rejected() -> None:
    with pytest.raises(ValueError, match="overlap"):
        chunk_lines(5000, window=100, overlap=200, threshold=10)
